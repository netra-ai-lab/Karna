#!/usr/bin/env bash
# One-off rebrand SOTA -> Karna: package sota -> karna, sota_train -> karna_train, class SOTA -> Karna,
# sota-base/-large -> karna-base/-large, SOTA_MODELS_DIR/SOTA_CACHE -> KARNA_*, *.sota.pt -> *.karna.pt.
#   scripts/rename_to_karna.sh <repo root> [--models-dir DIR]   (run from anywhere; idempotent)
# Checkpoints hold only tensors (no pickled sota classes), so existing .pt files load unchanged.
set -euo pipefail
ROOT=$(cd "${1:?usage: rename_to_karna.sh <repo root> [--models-dir DIR]}" && pwd)
MODELS_DIR=""; [ "${2:-}" = "--models-dir" ] && MODELS_DIR=${3:?}
cd "$ROOT"
mvp() { [ -e "$1" ] || return 0; if git ls-files --error-unmatch "$1" >/dev/null 2>&1; then git mv "$1" "$2"; else mv "$1" "$2"; fi; }
mvp sota karna
mvp training/sota_train training/karna_train
mvp training/release/cards/sota-base.md training/release/cards/karna-base.md
mvp training/release/cards/sota-large.md training/release/cards/karna-large.md
rm -rf netra_sota.egg-info build      # regenerated by the editable reinstall
# text files: tracked + untracked-not-ignored, plus the ignored local files that carry the names
{ git ls-files; git ls-files --others --exclude-standard; ls training/local.env training/local.env.example training/runs/*.sh 2>/dev/null; } \
  | sort -u | grep -v "scripts/rename_to_karna.sh" | while read -r f; do
    [ -f "$f" ] || continue
    case "$f" in *.png|*.jpg|*.pt|*.svg|*.pdf|*.ttf|*.woff*) continue;; esac
    grep -Iq . "$f" 2>/dev/null || continue                      # skip binaries
    grep -qiE "sota" "$f" || continue
    sed -i -E \
      -e 's/sota_train/karna_train/g; s/sota_local/karna_local/g' \
      -e 's/SOTA_MODELS_DIR/KARNA_MODELS_DIR/g; s/SOTA_CACHE/KARNA_CACHE/g' \
      -e 's/netra-sota/netra-karna/g; s/netra_sota/netra_karna/g' \
      -e 's#netra-ai-lab/(SOTA|Sota)#netra-ai-lab/Karna#g' \
      -e 's#Darayut/sota-(base|large)#Netra-Lab/karna-\1#g' \
      -e 's/\bSOTA\b/Karna/g; s/\bSota\b/Karna/g; s/\bsota\b/karna/g' "$f"
    echo "edited $f"
done
if [ -n "$MODELS_DIR" ]; then
    for p in "$MODELS_DIR"/*/*.sota.pt; do [ -e "$p" ] && mv -v "$p" "${p%.sota.pt}.karna.pt"; done
fi
echo "left with 'sota' (should be none outside run outputs):"
{ git ls-files; git ls-files --others --exclude-standard; } | grep -v "scripts/rename_to_karna.sh" | xargs grep -liE "sota" 2>/dev/null | grep -vE "\.(png|jpg|pt|svg)$" || true
